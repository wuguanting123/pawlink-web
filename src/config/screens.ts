export function resolveScreenMeta(pathname: string, search = ''): ScreenMeta {
  // Handle UI-02.05 empty search query state explicitly (?empty or ?empty=1)
  if (pathname === '/adopt/search' && new URLSearchParams(search).has('empty')) {
    return {
      id: 'UI-02.05',
      title: '搜尋無結果｜調整條件與保存搜尋',
      subtitle: '沒有符合條件的動物時提供明確空狀態，不顯示空白列表。',
      zone: 'adopt',
      pattern: '/adopt/search?empty',
      breadcrumbs: [
        { label: '領養專區', to: '/adopt' },
        { label: '進階篩選', to: '/adopt/search' },
        { label: '無結果' },
      ],
      prevId: 'UI-02.02',
      nextIds: ['UI-02.02'],
    };
  }

  // Handle shortcut application paths without :petId
  const shortcutApplyMap: Record<string, string> = {
    '/adopt/apply/contact': 'UI-02.11',
    '/adopt/apply/kyc': 'UI-02.12',
    '/adopt/apply/environment': 'UI-02.13',
    '/adopt/apply/education': 'UI-02.14',
    '/adopt/apply/contract': 'UI-02.15',
    '/adopt/apply/handover': 'UI-02.16',
  };
  if (shortcutApplyMap[pathname]) {
    const found = SCREEN_REGISTRY.find((s) => s.id === shortcutApplyMap[pathname]);
    if (found) return found;
  }

  for (const screen of SCREEN_REGISTRY) {
    if (matchPath({ path: screen.pattern, end: true }, pathname)) {
      return screen;
    }
  }

  return SCREEN_REGISTRY[6]; // Fallback to UI-01.00
}
